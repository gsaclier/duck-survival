export function mergeRoster(state) {
  if (state.rosterVersion >= rosterVersion) return state;
  const next = structuredClone(state);
  for (const seed of roster) {
    const existing = next.players.find(p => p.id === seed.id || p.name === seed.name);
    if (existing) {
      existing.rosterSnapshot ??= structuredClone(seed.rosterSnapshot);
      existing.reference ??= structuredClone(seed.reference);
    } else next.players.push(structuredClone(seed));
  }
  next.rosterVersion = rosterVersion;
  next.guildSnapshot ??= structuredClone(guildSnapshot);
  return next;
}
